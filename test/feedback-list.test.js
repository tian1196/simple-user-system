const { test } = require('node:test')
const assert = require('node:assert/strict')
const path = require('node:path')

test('my feedback recovers when the last page disappears, resets filters and ignores stale responses', async t => {
  const { createServer } = await import('../web/node_modules/vite/dist/node/index.js')
  const vite = await createServer({ configFile: path.resolve('web/vite.site.config.ts'), logLevel: 'error', server: { middlewareMode: true, hmr: false }, appType: 'custom' })
  t.after(() => vite.close())
  const { useFeedbackList } = await vite.ssrLoadModule('/src/composables/useFeedbackList.ts')
  const { nextTick } = await import('../web/node_modules/vue/index.mjs')
  const pending = []
  const list = useFeedbackList((params, signal) => new Promise((resolve, reject) => pending.push({ params, signal, resolve, reject })))
  t.after(list.dispose)
  const result = (total, page) => ({ items: Array.from({ length: Math.max(0, Math.min(10, total - (page - 1) * 10)) }, (_, i) => ({ id: `p${page}-${i}` })), total, page, page_size: 10, counts: { all: total, pending: total, processing: 0, resolved: 0 } })
  list.filter.value = 'pending'; await nextTick()
  pending.shift().resolve(result(11, 1)); await nextTick()
  list.page.value = 2; await nextTick()
  pending.shift().resolve(result(11, 2)); await nextTick()
  assert.equal(list.data.value.items.length, 1)
  const refreshed = list.load()
  pending.shift().resolve(result(10, 2)); await refreshed; await nextTick()
  assert.equal(list.page.value, 1, 'removing the final row of page 2 must expose page 1 again')
  const recovery = pending.shift(); assert.equal(recovery.params.page, 1)
  recovery.resolve(result(10, 1)); await nextTick()
  assert.equal(list.data.value.items.length, 10)
  list.page.value = 2; await nextTick()
  const stale = pending.shift()
  list.filter.value = 'resolved'; await nextTick()
  assert.equal(list.page.value, 1)
  const newest = pending.shift(); assert.equal(newest.params.status, 'resolved'); assert.equal(newest.params.page, 1)
  newest.resolve(result(1, 1)); await nextTick()
  stale.resolve(result(11, 2)); await nextTick()
  assert.equal(stale.signal.aborted, true)
  assert.equal(list.data.value.total, 1, 'late old-filter replies cannot replace the visible list')
  const failed = list.load(); pending.shift().reject(new Error('临时断网')); await failed
  assert.equal(list.error.value, '临时断网')
  assert.equal(list.data.value.total, 1, 'retry errors preserve the previous list')
  list.dispose()
  assert.equal(list.loading.value, false)
})
