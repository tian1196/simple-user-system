const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const { spawnSync } = require('node:child_process')
const { createHash } = require('node:crypto')
const { DatabaseSync } = require('node:sqlite')

test('deployment package includes both builds and excludes private local files', t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'ledger-pack-test-'))
  t.after(() => fs.rmSync(dir, { recursive: true, force: true }))
  function write(file, value = 'private-sentinel') {
    fs.mkdirSync(path.dirname(path.join(dir, file)), { recursive: true })
    fs.writeFileSync(path.join(dir, file), value)
  }
  for (const folder of ['server', 'public', 'migrations', 'deploy']) write(folder + '/sample.txt', 'source')
  write('scripts/pack.sh', fs.readFileSync('scripts/pack.sh'))
  write('package.json', '{"version":"1.0.0"}')
  write('package-lock.json', '{}')
  write('README.md', 'readme')
  write('.env.example', 'DATABASE_PATH=example')
  for (const file of ['.env', '.env.production', 'web/.env.local', 'web/site/.env.production', 'web/node_modules/secret.js', 'data/ledger.sqlite', 'server/copy.sqlite-wal', 'web/debug.log', 'dist/old.tar.gz', '.git/config']) write(file)
  for (const file of ['web/dist/index.html', 'web/site-dist/index.html', 'web/dist/assets/admin.js', 'web/site-dist/assets/site.js']) write(file, 'frontend')
  const result = spawnSync('sh', ['scripts/pack.sh', '--no-build'], { cwd: dir, encoding: 'utf8' })
  assert.equal(result.status, 0, result.stderr)
  const archive = path.join(dir, 'dist/device-ledger.tar.gz')
  const listed = spawnSync('tar', ['-tzf', archive], { encoding: 'utf8' })
  assert.equal(listed.status, 0)
  assert.match(listed.stdout, /web\/dist\/index.html/)
  assert.match(listed.stdout, /web\/site-dist\/index.html/)
  assert.match(listed.stdout, /\.env.example/)
  assert.doesNotMatch(listed.stdout, /node_modules|\.sqlite|\.log|\.git\/|old.tar|\.env\.(production|local)/)
  assert.ok(!listed.stdout.split('\n').includes('./.env'))
  assert.equal(fs.readFileSync(archive).includes(Buffer.from('private-sentinel')), false)
  const digest = createHash('sha256').update(fs.readFileSync(archive)).digest('hex')
  assert.equal(fs.readFileSync(archive + '.sha256', 'utf8'), `${digest}  device-ledger.tar.gz\n`)
  fs.unlinkSync(path.join(dir, 'web/site-dist/index.html'))
  const incomplete = spawnSync('sh', ['scripts/pack.sh', '--no-build'], { cwd: dir, encoding: 'utf8' })
  assert.notEqual(incomplete.status, 0, 'missing either frontend must fail')
})

test('database backup includes committed WAL writes and refuses overwrite', t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'ledger-backup-test-'))
  t.after(() => fs.rmSync(dir, { recursive: true, force: true }))
  const database = path.join(dir, 'source.sqlite')
  const env = { ...process.env, DATABASE_PATH: database }
  assert.equal(spawnSync(process.execPath, ['scripts/db-init.js'], { env }).status, 0)
  const source = new DatabaseSync(database)
  t.after(() => source.close())
  source.exec("PRAGMA journal_mode=WAL; INSERT INTO users(id,username,role) VALUES('backup-owner','backup_owner','admin')")
  const target = path.join(dir, 'backup.sqlite')
  const result = spawnSync(process.execPath, ['scripts/backup-database.js', target], { env, encoding: 'utf8' })
  assert.equal(result.status, 0, result.stderr)
  const snapshot = new DatabaseSync(target)
  assert.equal(snapshot.prepare('SELECT username FROM users').get().username, 'backup_owner')
  snapshot.close()
  assert.notEqual(spawnSync(process.execPath, ['scripts/backup-database.js', target], { env }).status, 0)
  assert.equal(source.prepare('SELECT count(*) AS n FROM users').get().n, 1)
})

test('deployment rejects missing host and invalid configuration before upload', () => {
  const help = spawnSync('bash', ['scripts/deploy.sh', '--help'], { encoding: 'utf8' })
  assert.equal(help.status, 0)
  for (const config of [{ DEPLOY_HOST: '' }, { DEPLOY_HOST: 'example.com', DEPLOY_DOMAIN: 'https://bad/path' }, { DEPLOY_HOST: 'example.com', DEPLOY_BASE: '/' }]) {
    assert.equal(spawnSync('bash', ['scripts/deploy.sh'], { env: { ...process.env, ...config } }).status, 2)
  }
})
